"""EXP30 -- anatomy of the BLOCK==SCHED stamping artifact.

The tail is generated by a data-recording artifact: when the airport has no real
off-block record it stamps BLOCK_TIME at SCHED_TIME, so y == off_sched exactly.
584 rows exceed 7200s and 481 of them have AOBT_3_flt missing, where
median |y - off_sched| = 4s.

This script measures the artifact event A = {|BLOCK - SCHED| <= 60s} directly:
its base rate, where it lives, how it clusters, and whether anything separates
an artifact row from a lookalike. No modelling -- just the numbers a classifier
would have to learn from.
"""
import os, sys, time
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import numpy as np, pandas as pd
from prc.config import TARGET, TAIL_CAP
from prc.features import NEEDED
from prc.io import load, peak_rss_gb
pd.set_option('display.width', 220)

t0 = time.time()
cols = sorted(set(NEEDED + [TARGET, 'BLOCK_TIME_UTC_mvt', 'IOBT_flt',
                            'ARVT_1_flt', 'ARVT_3_flt', 'CALLSIGN_flt',
                            'FLIGHT_RULE_mvt', 'ADES_mvt']))
tr = load('training', phase='DEP', columns=cols)
n = len(tr)
y = tr[TARGET].astype(float).to_numpy()
delta = (tr.BLOCK_TIME_UTC_mvt - tr.SCHED_TIME_UTC_mvt).dt.total_seconds().to_numpy()
off_sched = (tr.MVT_TIME_UTC_mvt - tr.SCHED_TIME_UTC_mvt).dt.total_seconds().to_numpy()
off_aobt3 = (tr.MVT_TIME_UTC_mvt - tr.AOBT_3_flt).dt.total_seconds().to_numpy()
aobt_miss = tr.AOBT_3_flt.isna().to_numpy()
apt = tr.APT.astype(str).to_numpy()
month = tr.MVT_TIME_UTC_mvt.dt.month.to_numpy()
day = tr.MVT_TIME_UTC_mvt.dt.floor('D')
tail = y > TAIL_CAP
print(f'{n:,} departures, {int(tail.sum())} tail rows  ({time.time()-t0:.0f}s)')

# identity check: y == off_sched - delta ?
resid = y - (off_sched - delta)
print(f'\nidentity y == off_sched - delta : max |resid| = {np.nanmax(np.abs(resid)):.1f}s, '
      f'nonzero {int((np.abs(resid) > 0.5).sum())}')

print('\n' + '=' * 100)
print('1. THE ARTIFACT EVENT A = |BLOCK - SCHED| <= tol')
print('=' * 100)
for tol in [0, 1, 5, 30, 60, 120, 300]:
    A = np.abs(delta) <= tol
    print(f'  tol {tol:4d}s : n={int(A.sum()):8,} ({A.mean()*100:6.3f}%)   '
          f'of tail rows: {int(A[tail].sum()):3d}/{int(tail.sum())} ({A[tail].mean()*100:5.1f}%)')

TOL = 60
A = np.abs(delta) <= TOL
print(f'\n  using tol={TOL}s -> base rate {A.mean()*100:.3f}%  ({int(A.sum()):,} rows)')
print(f'  P(tail | A)        = {tail[A].mean()*100:.4f}%   ({int(tail[A].sum())} of {int(A.sum()):,})')
print(f'  P(A | tail)        = {A[tail].mean()*100:.1f}%')
print(f'  P(A | aobt_miss)   = {A[aobt_miss].mean()*100:.2f}%   (n={int(aobt_miss.sum()):,})')
print(f'  P(A | aobt_present)= {A[~aobt_miss].mean()*100:.2f}%')

print('\n--- per airport ---')
rows = []
for a in sorted(set(apt)):
    s = apt == a
    rows.append(dict(apt=a, n=int(s.sum()), pA=A[s].mean() * 100,
                     p_exact=(np.abs(delta[s]) <= 1).mean() * 100,
                     aobt_miss=aobt_miss[s].mean() * 100,
                     n_tail=int(tail[s].sum()),
                     pA_given_miss=A[s & aobt_miss].mean() * 100 if (s & aobt_miss).any() else np.nan))
print(pd.DataFrame(rows).round(2).to_string(index=False))

print('\n' + '=' * 100)
print('2. WHERE THE TAIL LIVES: joint structure of (aobt_miss, off_sched)')
print('=' * 100)
bins = [-np.inf, 1800, 3600, 7200, 14400, 28800, 57600, np.inf]
lab = ['<30m', '30-60m', '1-2h', '2-4h', '4-8h', '8-16h', '>16h']
ob = np.asarray(pd.cut(off_sched, bins, labels=lab))
for miss in [True, False]:
    print(f'\n  aobt_missing = {miss}  (n={int((aobt_miss==miss).sum()):,})')
    out = []
    for l in lab:
        s = (ob == l) & (aobt_miss == miss)
        if s.sum() == 0:
            continue
        out.append(dict(off_sched=l, n=int(s.sum()), pA=A[s].mean() * 100,
                        p_tail=tail[s].mean() * 100, n_tail=int(tail[s].sum()),
                        med_y=float(np.median(y[s]))))
    print(pd.DataFrame(out).round(3).to_string(index=False))

print('\n--- exact distribution of delta = BLOCK - SCHED on TAIL rows ---')
dt_t = delta[tail]
vc = pd.Series(dt_t).round().astype(int).value_counts().head(20)
print('  most common delta values (s):')
print('   ', dict(vc))
print(f'  |delta| percentiles on tail rows: p10 {np.percentile(np.abs(dt_t),10):.0f} '
      f'p50 {np.percentile(np.abs(dt_t),50):.0f} p90 {np.percentile(np.abs(dt_t),90):.0f} '
      f'p99 {np.percentile(np.abs(dt_t),99):.0f} max {np.abs(dt_t).max():.0f}')
print('  same for ALL rows:')
print(f'  |delta| percentiles all rows : p10 {np.percentile(np.abs(delta),10):.0f} '
      f'p50 {np.percentile(np.abs(delta),50):.0f} p90 {np.percentile(np.abs(delta),90):.0f}')

print('\n--- LIRF, the airport that owns the tail ---')
li = apt == 'LIRF'
print(f'  LIRF n={int(li.sum()):,}  tail {int(tail[li].sum())}  aobt_miss {int((li&aobt_miss).sum()):,}')
for nm, s_ in [('aobt_miss', li & aobt_miss), ('aobt_present', li & ~aobt_miss)]:
    print(f'    {nm:14s} n={int(s_.sum()):7,}  P(A)={A[s_].mean()*100:6.2f}%  '
          f'P(tail)={tail[s_].mean()*100:6.3f}%  n_tail={int(tail[s_].sum())}')
    for l in lab:
        ss = s_ & (ob == l)
        if ss.sum() == 0: continue
        print(f'       off_sched {l:7s} n={int(ss.sum()):7,}  P(A)={A[ss].mean()*100:6.2f}%  '
              f'P(tail)={tail[ss].mean()*100:6.2f}%  n_tail={int(tail[ss].sum()):3d}  '
              f'med_y={np.median(y[ss]):7.0f}')

print('\n' + '=' * 100)
print('3. IS THE ARTIFACT BURSTY?  (clustering by airport-day / airport-hour)')
print('=' * 100)
df = pd.DataFrame({'apt': apt, 'day': day.to_numpy(), 'A': A.astype(float),
                   'miss': aobt_miss.astype(float), 'tail': tail.astype(float)})
g = df.groupby(['apt', 'day'], observed=True).agg(n=('A', 'size'), rA=('A', 'mean'),
                                                  rM=('miss', 'mean'), nt=('tail', 'sum'))
g = g[g.n >= 20]
print(f'  {len(g):,} airport-days with >=20 departures')
print(f'  artifact rate per airport-day: mean {g.rA.mean()*100:.2f}%  '
      f'sd {g.rA.std()*100:.2f}%  p50 {g.rA.median()*100:.2f}%  '
      f'p95 {g.rA.quantile(.95)*100:.2f}%  p99 {g.rA.quantile(.99)*100:.2f}%  max {g.rA.max()*100:.1f}%')
print(f'  aobt-missing rate per airport-day: mean {g.rM.mean()*100:.2f}%  '
      f'sd {g.rM.std()*100:.2f}%  p95 {g.rM.quantile(.95)*100:.2f}%  max {g.rM.max()*100:.1f}%')
print(f'  corr(artifact rate, aobt-missing rate) across airport-days = '
      f'{np.corrcoef(g.rA, g.rM)[0,1]:.3f}')
# binomial overdispersion: if A were iid within airport, var of the day rate would be p(1-p)/n
for a in sorted(set(apt)):
    ga = g[g.index.get_level_values('apt') == a]
    p = ga.rA.mean()
    exp_var = (p * (1 - p) / ga.n).mean()
    print(f'    {a}: mean {p*100:5.2f}%  observed var {ga.rA.var():.6f}  '
          f'iid var {exp_var:.6f}  overdispersion {ga.rA.var()/max(exp_var,1e-12):6.1f}x')

print('\n  --- days that carry the tail rows ---')
gt = g[g.nt > 0].sort_values('nt', ascending=False)
print(f'  {len(gt)} airport-days contain the {int(g.nt.sum())} tail rows '
      f'(of {len(g):,} airport-days)')
print(gt.head(15).assign(rA=lambda d: (d.rA*100).round(1), rM=lambda d: (d.rM*100).round(1))
      .to_string())

print('\n' + '=' * 100)
print('4. THE 481 aobt_missing TAIL ROWS vs THEIR LOOKALIKES')
print('=' * 100)
# lookalike population: aobt_missing AND off_sched > 7200 but NOT tail
look = aobt_miss & (off_sched > TAIL_CAP)
print(f'  aobt_miss & off_sched>7200 : n={int(look.sum()):,}, of which tail '
      f'{int(tail[look].sum())} ({tail[look].mean()*100:.1f}%)  -- the 45% coin flip')
sub = pd.DataFrame({
    'off_sched': off_sched[look], 'y': y[look], 'istail': tail[look], 'A': A[look],
    'apt': apt[look], 'hour': tr.MVT_TIME_UTC_mvt.dt.hour.to_numpy()[look],
    'month': month[look],
    'lobt_miss': tr.LOBT_flt.isna().to_numpy()[look],
    'eobt_miss': tr.EOBT_1_flt.isna().to_numpy()[look],
    'iobt_miss': tr.IOBT_flt.isna().to_numpy()[look],
    'arvt1_miss': tr.ARVT_1_flt.isna().to_numpy()[look],
    'arvt3_miss': tr.ARVT_3_flt.isna().to_numpy()[look],
    'stand_na': tr.STAND_mvt.isna().to_numpy()[look],
    'rwy_na': tr.RUNWAY_mvt.isna().to_numpy()[look],
    'op': tr.AIRCRAFT_OPERATOR_flt.astype(str).to_numpy()[look],
    'seg': tr.MARKET_SEGMENT_flt.astype(str).to_numpy()[look],
})
print('\n  missingness of other columns, tail vs not (within the lookalike set):')
for c in ['lobt_miss', 'eobt_miss', 'iobt_miss', 'arvt1_miss', 'arvt3_miss',
          'stand_na', 'rwy_na']:
    print(f'    {c:12s}  tail {sub.loc[sub.istail, c].mean()*100:6.2f}%   '
          f'not-tail {sub.loc[~sub.istail, c].mean()*100:6.2f}%')
print('\n  by airport:')
print(sub.groupby('apt').agg(n=('istail', 'size'), p_tail=('istail', 'mean'),
                             pA=('A', 'mean')).assign(
    p_tail=lambda d: (d.p_tail*100).round(1), pA=lambda d: (d.pA*100).round(1)).to_string())
print('\n  by month:')
print(sub.groupby('month').agg(n=('istail', 'size'), p_tail=('istail', 'mean')).assign(
    p_tail=lambda d: (d.p_tail*100).round(1)).to_string())
print('\n  by off_sched decile:')
sub['osd'] = pd.qcut(sub.off_sched, 10, duplicates='drop')
print(sub.groupby('osd', observed=True).agg(n=('istail', 'size'), p_tail=('istail', 'mean'),
                                            pA=('A', 'mean')).assign(
    p_tail=lambda d: (d.p_tail*100).round(1), pA=lambda d: (d.pA*100).round(1)).to_string())
print('\n  by market segment:')
print(sub.groupby('seg').agg(n=('istail', 'size'), p_tail=('istail', 'mean')).assign(
    p_tail=lambda d: (d.p_tail*100).round(1)).sort_values('n', ascending=False).head(10).to_string())

print('\n' + '=' * 100)
print('5. WHAT DOES y LOOK LIKE FOR THE NON-ARTIFACT LOOKALIKES?')
print('=' * 100)
nt = look & ~tail
print(f'  n={int(nt.sum()):,}  y: p10 {np.percentile(y[nt],10):.0f}  p50 '
      f'{np.percentile(y[nt],50):.0f}  p90 {np.percentile(y[nt],90):.0f}  max {y[nt].max():.0f}')
print(f'  overall bulk y: p50 {np.percentile(y[~tail],50):.0f}  '
      f'p90 {np.percentile(y[~tail],90):.0f}')
print(f'  delta (=BLOCK-SCHED) for these rows: p10 {np.percentile(delta[nt],10):.0f} '
      f'p50 {np.percentile(delta[nt],50):.0f} p90 {np.percentile(delta[nt],90):.0f}')

print(f'\npeak RSS = {peak_rss_gb():.2f} GB  total {time.time()-t0:.0f}s')
